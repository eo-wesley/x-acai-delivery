import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import { buildMenuPrices, menuPricesCsv, parseMenuPrice } from '../src/lib/menu-prices.ts';

const snapshot = JSON.parse(await fs.readFile(new URL('../src/data/xacai-pricing-snapshot.json', import.meta.url), 'utf8'));
const original = JSON.stringify(snapshot);
const rows = buildMenuPrices(snapshot);
const byId = id => rows.find(row => row.id === id);
assert.equal(rows.length, 89);
assert.equal(new Set(rows.map(row => row.id)).size, rows.length);
assert.equal(rows.filter(row => row.status === 'approved').length, 29);
assert.equal(rows.filter(row => row.status === 'proposed').length, 1);
assert.equal(byId('MONTE-700').price, 38.9);
assert.equal(byId('MARMITEX-700').price, 38.9);
assert.equal(byId('MARMITEX-700').approvedPrice, null);
assert.equal(byId('MARMITEX-700').status, 'proposed');
assert.deepEqual([300, 400, 500, 700].map(size => byId(`COMBO-${size}`).price), [23.9, 29.9, 36.9, 49.9]);
assert.deepEqual([300, 400, 500, 700].map(size => byId(`X-PACOKITA-${size}`).price), [12.9, 15.9, 19.9, 26.9]);
assert.equal(byId('X-PACOLEITE-300').status, 'legacy');
assert.equal(byId('X-PACOLEITE-300').price, 26.9);
assert.equal(byId('BEB-COCA-COLA-350ML').price, 10);
assert.equal(byId('BEB-COCA-COLA-350ML').status, 'legacy');
for (const value of ['', '0', '-1', 'NaN', 'Infinity', '1e3', '12.345', '1,2,3', '10000']) assert.equal(parseMenuPrice(value), null, value);
assert.equal(parseMenuPrice(' 12,90 '), 12.9);
assert.equal(parseMenuPrice('19.9'), 19.9);
const draftCsv = menuPricesCsv(rows, { 'X-PACOKITA-300': '13.90' });
assert.match(draftCsv, /13,90/);
assert.match(draftCsv, /Rascunho editado/);
assert.equal(byId('X-PACOKITA-300').approvedPrice, 12.9);
assert.equal(JSON.stringify(snapshot), original);
console.log('Menu: completude, aprovação, recomendações, legado, edição e exportação validados.');
